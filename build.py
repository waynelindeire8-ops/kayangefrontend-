#!/usr/bin/env python3
"""Build the Kayange static frontend into ./dist (deploy that folder to Cloudflare Pages).

    pip install jinja2
    python build.py --api-base https://api.yourdomain.com

--api-base can also come from the API_BASE_URL environment variable.
Every page of the app is rendered once into dist/_pages/ and exposed on its
real URL through Cloudflare's _redirects file (200 = rewrite, URL stays the same).
Pages that take a record id (/patients/12/edit) share one HTML file; the id is
read from the URL in the browser (see src/static/js/config.js).
"""
import argparse, json, os, re, shutil, sys
from jinja2 import Environment, FileSystemLoader

HERE = os.path.dirname(os.path.abspath(__file__))
SRC, DIST = os.path.join(HERE, 'src'), os.path.join(HERE, 'dist')

ap = argparse.ArgumentParser()
ap.add_argument('--api-base', default=os.environ.get('API_BASE_URL', ''))
args = ap.parse_args()
api_base = args.api_base.rstrip('/')
if not api_base:
    print('ERROR: pass --api-base https://api.yourdomain.com (or set API_BASE_URL)'); sys.exit(1)

env = Environment(loader=FileSystemLoader(os.path.join(SRC, 'templates')), autoescape=False, keep_trailing_newline=True)
env.globals['url_for'] = lambda endpoint, filename='': '/static/' + filename

routes = json.load(open(os.path.join(HERE, 'routes.json')))

shutil.rmtree(DIST, ignore_errors=True)
os.makedirs(os.path.join(DIST, '_pages'))
shutil.copytree(os.path.join(SRC, 'static'), os.path.join(DIST, 'static'))

def slug(rule):
    s = re.sub(r'<(?:\w+:)?(\w+)>', r'\1', rule).strip('/').replace('/', '_')
    return s or 'home'

static_rules, dynamic_rules, written, used = [], [], {}, set()
for r in routes:
    rule, tmpl = r['rule'], r['template']
    name = slug(rule)
    html = env.get_template(tmpl).render()
    with open(os.path.join(DIST, '_pages', name + '.html'), 'w', encoding='utf-8') as f:
        f.write(html)
    used.add(tmpl)
    dest = '/_pages/%s.html' % name
    pattern = re.sub(r'<(?:\w+:)?(\w+)>', r':\1', rule)
    if ':' in pattern:
        dynamic_rules.append((pattern, dest))
    else:
        static_rules.append((pattern, dest))
        static_rules.append((pattern + '/', dest))

# 404 page
with open(os.path.join(DIST, '404.html'), 'w', encoding='utf-8') as f:
    f.write(env.get_template('error.html').render())
used |= {'error.html', 'base.html'}

unrouted = sorted(
    os.path.relpath(os.path.join(d, f), os.path.join(SRC, 'templates')).replace('\\', '/')
    for d, _, fs in os.walk(os.path.join(SRC, 'templates')) for f in fs if f.endswith('.html'))
unrouted = [t for t in unrouted if t not in used]
if unrouted:
    print('WARNING: templates with no route:', unrouted)

with open(os.path.join(DIST, '_redirects'), 'w', encoding='utf-8') as f:
    f.write('/  /dashboard  302\n')
    for a, b in static_rules: f.write('%s  %s  200\n' % (a, b))
    for a, b in dynamic_rules: f.write('%s  %s  200\n' % (a, b))
if len(dynamic_rules) > 100:
    print('WARNING: Cloudflare allows 100 dynamic redirect rules; you have', len(dynamic_rules))

with open(os.path.join(DIST, 'env.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by build.py - edit this file to point the UI at a different API.\n')
    f.write('window.KAYANGE_API_BASE = %s;\n' % json.dumps(api_base))

with open(os.path.join(DIST, '_headers'), 'w', encoding='utf-8') as f:
    f.write('''/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: SAMEORIGIN
  Referrer-Policy: strict-origin-when-cross-origin
/_pages/*
  Cache-Control: no-cache
/env.js
  Cache-Control: no-store
/static/*
  Cache-Control: public, max-age=300
''')

print('Built %d pages -> %s (API: %s)' % (len(routes), DIST, api_base))
print('Static rules: %d, dynamic rules: %d' % (len(static_rules) + 1, len(dynamic_rules)))
